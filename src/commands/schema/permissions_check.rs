//! What `schema doctor` and `schema rules` say about permissions, read from the consumer's source.
//!
//! The schema says what every generated route requires; this reads the hand-written side of the
//! tree for the places a request can reach a handler with no permission check:
//!
//! - a `.route(..)` in hand code whose handler is not wrapped in `guarded(..)` (or `guarded_all`,
//!   `guarded_needs`), unless the line says `// unguarded: <why>`;
//! - a direct call of the framework's unguarded generic routes (`BackboneCrudHandler::routes`,
//!   `read_routes`, `write_routes`), which check nothing;
//! - a permission named in a `guarded(..)` or `.require(..)` call that the module's vocabulary does
//!   not hold.
//!
//! It also decides which *mode* the tree is in: whether a grant resolver is installed (permissions
//! are read from the identity tables once per request) or not (permissions are whatever the host's
//! authentication put on the `AuthContext`). Nothing is allowed by default in either.

use std::collections::{BTreeSet, HashSet};
use std::path::{Path, PathBuf};

use regex::Regex;
use walkdir::WalkDir;

/// Where permissions come from at run time.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Mode {
    /// A grant resolver is installed: permissions are loaded from the identity tables per request.
    Resolver,
    /// No resolver: permissions are read from `AuthContext` as the host's authentication provides
    /// them. A caller whose context holds none is refused.
    AuthContext,
}

impl Mode {
    /// The label `schema rules` and `schema doctor` print.
    pub fn label(&self) -> &'static str {
        match self {
            Mode::Resolver => "RESOLVER (grants loaded from the identity tables once per request)",
            Mode::AuthContext => "AUTHCONTEXT (permissions read as the host's authentication provides them; no grant resolver installed, nothing allowed by default)",
        }
    }
}

/// One hand-written `.route(..)` or unguarded generic route call.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct HandRoute {
    pub file: String,
    pub line: usize,
    /// The route's path literal, or the call's name.
    pub what: String,
    pub guarded: bool,
    /// The reason given by an `// unguarded: <why>` marker.
    pub acknowledged: Option<String>,
}

/// A permission a hand-written guard names.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct NamedPermission {
    pub file: String,
    pub line: usize,
    pub permission: String,
}

/// What the tree's source does with permissions.
#[derive(Debug, Default)]
pub struct SourceReport {
    pub mode: Option<Mode>,
    pub routes: Vec<HandRoute>,
    pub named: Vec<NamedPermission>,
}

fn is_generated(content: &str) -> bool {
    content
        .lines()
        .take(8)
        .any(|l| l.contains("Generated by metaphor-schema"))
}

/// The text of the call whose `(` is at `open`, through its matching `)`.
fn balanced(text: &str, open: usize) -> &str {
    let bytes = text.as_bytes();
    let mut depth = 0usize;
    let mut in_str = false;
    let mut i = open;
    while i < bytes.len() {
        match bytes[i] {
            b'\\' if in_str => i += 1,
            b'"' => in_str = !in_str,
            b'(' if !in_str => depth += 1,
            b')' if !in_str => {
                depth -= 1;
                if depth == 0 {
                    return &text[open..=i];
                }
            }
            _ => {}
        }
        i += 1;
    }
    &text[open..]
}

fn line_of(text: &str, offset: usize) -> usize {
    text[..offset].bytes().filter(|b| *b == b'\n').count() + 1
}

/// The files under `src` that are compiled only for tests: those a parent declares as
/// `#[cfg(test)] mod name;` (with or without a `#[path = ".."]`), those carrying the inner
/// attribute `#![cfg(test)]`, and every file such a file declares in turn. A test module in its own
/// file has no `#[cfg(test)]` of its own to cut at, so the scan would otherwise read it as hand code.
fn test_only_files(src: &Path) -> HashSet<PathBuf> {
    let cfg_test_mod = Regex::new(
        r#"#\[cfg\(test\)\]\s*(?:#\[path\s*=\s*"([^"]+)"\]\s*)?(?:pub(?:\([^)]*\))?\s+)?mod\s+(\w+)\s*;"#,
    )
    .unwrap();
    let any_mod =
        Regex::new(r"(?m)^\s*(?:pub(?:\([^)]*\))?\s+)?mod\s+(\w+)\s*;").unwrap();

    // The files `parent` declares as `mod name;`, found where the module system looks for them.
    let declared = |parent: &Path, name: &str, path_attr: Option<&str>| -> Vec<PathBuf> {
        let dir = parent.parent().unwrap_or(Path::new(""));
        if let Some(rel) = path_attr {
            return vec![dir.join(rel)];
        }
        let base = match parent.file_stem().and_then(|s| s.to_str()) {
            Some("mod") | Some("lib") | Some("main") => dir.to_path_buf(),
            Some(stem) => dir.join(stem),
            None => dir.to_path_buf(),
        };
        vec![
            base.join(format!("{name}.rs")),
            base.join(name).join("mod.rs"),
        ]
    };

    let mut files: Vec<(PathBuf, String)> = Vec::new();
    for entry in WalkDir::new(src).follow_links(false).into_iter().flatten() {
        let path = entry.path();
        if path.is_file() && path.extension().and_then(|e| e.to_str()) == Some("rs") {
            if let Ok(text) = std::fs::read_to_string(path) {
                files.push((path.to_path_buf(), text));
            }
        }
    }

    let mut test_only: HashSet<PathBuf> = HashSet::new();
    for (path, text) in &files {
        if text.contains("#![cfg(test)]") {
            test_only.insert(path.clone());
        }
        for c in cfg_test_mod.captures_iter(text) {
            let name = &c[2];
            let path_attr = c.get(1).map(|m| m.as_str());
            for child in declared(path, name, path_attr) {
                if child.is_file() {
                    test_only.insert(child);
                }
            }
        }
    }

    // A file only a test file can reach is test code too.
    loop {
        let before = test_only.len();
        for (path, text) in &files {
            if !test_only.contains(path) {
                continue;
            }
            for c in any_mod.captures_iter(text) {
                for child in declared(path, &c[1], None) {
                    if child.is_file() {
                        test_only.insert(child);
                    }
                }
            }
        }
        if test_only.len() == before {
            break;
        }
    }
    test_only
}

/// Read the hand-written source under `root/src`.
pub fn scan(root: &Path) -> SourceReport {
    let mut report = SourceReport::default();
    let test_files = test_only_files(&root.join("src"));
    let route_call = Regex::new(r"\.route\(").unwrap();
    let guard_call = Regex::new(r"\bguarded(?:_all|_needs|_with)?\(").unwrap();
    let require_call = Regex::new(r"\.require(?:_with)?\(").unwrap();
    let crud_call = Regex::new(
        r"BackboneCrudHandler\s*::\s*<[^;]*?>\s*::\s*(routes|read_routes|write_routes)\(",
    )
    .unwrap();
    let literal = Regex::new(r#""([a-z0-9_*]+[:.][a-z0-9_*]+)""#).unwrap();
    let path_literal = Regex::new(r#"^\(\s*(?:&format!\()?\s*"([^"]*)""#).unwrap();
    let mut resolver = false;

    for entry in WalkDir::new(root.join("src"))
        .follow_links(false)
        .into_iter()
        .flatten()
    {
        let path = entry.path();
        if !path.is_file() || path.extension().and_then(|e| e.to_str()) != Some("rs") {
            continue;
        }
        if test_files.contains(path) {
            continue;
        }
        let Ok(full) = std::fs::read_to_string(path) else {
            continue;
        };
        if is_generated(&full) {
            continue;
        }
        // The hand code a request reaches, not its unit tests, and not what a comment says.
        let original = full.split("#[cfg(test)]").next().unwrap_or(&full);
        let blanked: String = original
            .lines()
            .map(|l| {
                if l.trim_start().starts_with("//") {
                    ""
                } else {
                    l
                }
            })
            .collect::<Vec<_>>()
            .join("\n");
        let text = blanked.as_str();
        let rel = path
            .strip_prefix(root)
            .unwrap_or(path)
            .display()
            .to_string();
        if text.contains("resolve_grants") || text.contains("GrantResolver") {
            resolver = true;
        }
        let lines: Vec<&str> = original.lines().collect();
        let marker = |line: usize, end_line: usize| -> Option<String> {
            // On the call's lines or the line above.
            for l in line.saturating_sub(1)..=end_line {
                if let Some(text) = lines.get(l.saturating_sub(1)) {
                    if let Some((_, why)) = text.split_once("// unguarded:") {
                        return Some(why.trim().to_string());
                    }
                }
            }
            None
        };
        for m in route_call.find_iter(text) {
            let open = m.end() - 1;
            let call = balanced(text, open);
            let line = line_of(text, m.start());
            let end_line = line_of(text, (open + call.len()).min(text.len().saturating_sub(1)));
            let what = path_literal
                .captures(call)
                .map(|c| c[1].to_string())
                .unwrap_or_else(|| call.chars().take(40).collect());
            // The handler is the call's second argument: guarded when it contains a guard call, or
            // is a name bound to one.
            let guarded = guard_call.is_match(call) || {
                let after_first = call
                    .split_once(',')
                    .map(|(_, rest)| rest.trim().trim_end_matches(')').trim())
                    .unwrap_or("");
                !after_first.is_empty()
                    && after_first.chars().all(|c| c.is_alphanumeric() || c == '_')
                    && Regex::new(&format!(
                        r"let\s+(?:mut\s+)?{}\b[^;]*?guarded",
                        regex::escape(after_first)
                    ))
                    .map(|re| re.is_match(text))
                    .unwrap_or(false)
            };
            report.routes.push(HandRoute {
                file: rel.clone(),
                line,
                what,
                guarded,
                acknowledged: marker(line, end_line),
            });
        }
        for m in crud_call.captures_iter(text) {
            let whole = m.get(0).unwrap();
            let line = line_of(text, whole.start());
            report.routes.push(HandRoute {
                file: rel.clone(),
                line,
                what: format!("BackboneCrudHandler::{}", &m[1]),
                guarded: false,
                acknowledged: marker(line, line),
            });
        }
        for m in guard_call
            .find_iter(text)
            .chain(require_call.find_iter(text))
        {
            let call = balanced(text, m.end() - 1);
            let line = line_of(text, m.start());
            for l in literal.captures_iter(call) {
                report.named.push(NamedPermission {
                    file: rel.clone(),
                    line,
                    permission: l[1].to_string(),
                });
            }
        }
    }
    report.mode = Some(if resolver {
        Mode::Resolver
    } else {
        Mode::AuthContext
    });
    report
}

/// The permissions hand code names that the vocabulary lacks, normalised the way the schema does.
pub fn undeclared(
    report: &SourceReport,
    rbac: &crate::rbac::Rbac,
    vocabulary: &BTreeSet<String>,
) -> Vec<NamedPermission> {
    let mut out = Vec::new();
    for n in &report.named {
        let Some(c) = rbac.canonical(&n.permission) else {
            continue;
        };
        let known = vocabulary.contains(&c.permission)
            || c.permission.starts_with("*:")
            || c.permission.ends_with(":*");
        if !known
            && !out
                .iter()
                .any(|o: &NamedPermission| o.permission == n.permission)
        {
            out.push(n.clone());
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn tree(files: &[(&str, &str)]) -> tempfile::TempDir {
        let dir = tempfile::tempdir().unwrap();
        for (name, body) in files {
            let path = dir.path().join(name);
            std::fs::create_dir_all(path.parent().unwrap()).unwrap();
            std::fs::write(path, body).unwrap();
        }
        dir
    }

    #[test]
    fn a_hand_route_is_guarded_when_its_handler_is_wrapped() {
        let dir = tree(&[(
            "src/x.ext.rs",
            "fn r() -> Router {\n  Router::new()\n    .route(\"/a\", guarded(post(a), \"ticket:escalate\"))\n    .route(\"/b\", post(b))\n    .route(\n        \"/c\",\n        guarded_all(post(c), &[\"ticket:read\", \"ticket:update\"]),\n    )\n}\n",
        )]);
        let r = scan(dir.path());
        let by: Vec<(&str, bool)> = r
            .routes
            .iter()
            .map(|x| (x.what.as_str(), x.guarded))
            .collect();
        assert_eq!(by, vec![("/a", true), ("/b", false), ("/c", true)]);
        assert_eq!(r.routes[1].line, 4);
        let perms: Vec<&str> = r.named.iter().map(|n| n.permission.as_str()).collect();
        assert_eq!(
            perms,
            vec!["ticket:escalate", "ticket:read", "ticket:update"]
        );
    }

    #[test]
    fn a_file_declared_as_a_cfg_test_module_is_test_code_and_not_scanned() {
        let hand = "fn r() { Router::new().route(\"/real\", post(h)); }\n";
        let fixture = "fn f() { Router::new().route(\"/fixture\", guarded(get(g), \"thing:read\")); }\n";
        let dir = tree(&[
            (
                "src/lib.rs",
                "pub mod live;\n#[cfg(test)]\nmod tests;\n#[cfg(test)]\n#[path = \"odd_name.rs\"]\nmod renamed;\n",
            ),
            ("src/live.rs", hand),
            ("src/tests.rs", &format!("mod nested;\n{fixture}")),
            ("src/tests/nested.rs", fixture),
            ("src/odd_name.rs", fixture),
            ("src/inner.rs", &format!("#![cfg(test)]\n{fixture}")),
        ]);
        let r = scan(dir.path());
        assert_eq!(
            r.routes.iter().map(|x| x.what.as_str()).collect::<Vec<_>>(),
            vec!["/real"]
        );
        assert!(r.named.is_empty());
    }

    #[test]
    fn a_route_built_earlier_and_named_counts_when_it_was_guarded() {
        let dir = tree(&[(
            "src/x.ext.rs",
            "fn r() {\n  let ok = guarded(post(a), \"t:x\");\n  let bad = post(b);\n  Router::new().route(\"/a\", ok).route(\"/b\", bad);\n}\n",
        )]);
        let r = scan(dir.path());
        assert_eq!(
            r.routes.iter().map(|x| x.guarded).collect::<Vec<_>>(),
            vec![true, false]
        );
    }

    #[test]
    fn an_acknowledged_route_carries_its_reason_and_generated_and_test_code_is_skipped() {
        let dir = tree(&[
            ("src/x.ext.rs", "fn r() {\n  // unguarded: the provider's callback is verified by its signature\n  Router::new().route(\"/hook\", post(h));\n}\n#[cfg(test)]\nmod t { fn x() { Router::new().route(\"/t\", get(t)); } }\n"),
            ("src/gen.rs", "//! Generated by metaphor-schema. Do not edit manually.\nfn r() { Router::new().route(\"/g\", get(g)); }\n"),
        ]);
        let r = scan(dir.path());
        assert_eq!(r.routes.len(), 1);
        assert_eq!(
            r.routes[0].acknowledged.as_deref(),
            Some("the provider's callback is verified by its signature")
        );
    }

    #[test]
    fn a_direct_call_of_the_unguarded_generic_routes_is_a_hand_route() {
        let dir = tree(&[(
            "src/x.ext.rs",
            "fn r(s: Arc<S>) -> Router {\n  BackboneCrudHandler::<S, E, C, U, R>::routes(s, \"/things\")\n}\nfn g(s: Arc<S>) -> Router {\n  BackboneCrudHandler::<S, E, C, U, R>::routes_guarded(s, \"/things\", p())\n}\n",
        )]);
        let r = scan(dir.path());
        assert_eq!(r.routes.len(), 1);
        assert!(!r.routes[0].guarded && r.routes[0].what.ends_with("routes"));
    }

    #[test]
    fn the_mode_follows_whether_a_resolver_is_installed() {
        let none = tree(&[("src/main.rs", "fn main() {}\n")]);
        assert_eq!(scan(none.path()).mode, Some(Mode::AuthContext));
        let some = tree(&[("src/main.rs", "fn main() { let r = GrantResolver::new(src); app.route_layer(from_fn_with_state(r, resolve_grants)); }\n")]);
        assert_eq!(scan(some.path()).mode, Some(Mode::Resolver));
    }
}
