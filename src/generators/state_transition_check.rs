//! State Transition Check Generator
//!
//! For every model with a state machine its hook files declare, emits ONE migration attaching a
//! `BEFORE UPDATE OF <state field>` trigger that compares the move `OLD -> NEW` with the
//! machine's declared transitions. A move the machine does not declare is refused: the trigger
//! raises a `check_violation` naming the state column and the constraint
//! `tg_<table>__state_transition_not_declared`, which the framework answers as a 422 violation on
//! that field. It covers every writer, hand-written SQL included.
//!
//! Per-table migrations named `state_transition_check_<table>_<digest>`: the digest covers the
//! migration's text, so a machine that declares another move, or a change to how the check
//! answers, lands as a new forward migration replacing the function, never as a rewrite of an
//! applied one. Earlier `add_state_transition_check_<table>` migrations stay as they were.
//!
//! The machines come from the rule register, which reads every hook format: a transition from
//! `*` allows any source state, and the state `null` stands for an unset column.
//!
//! A machine is checked only when its states are the values its column holds: an enum or text
//! field, or a bool field whose states are `true` and `false`. A bool field with named states
//! (`enforced`/`unenforced`) cannot be compared, and a trigger would warn on every legitimate
//! toggle; such a machine gets a `drop_state_transition_check_<table>` migration instead, which
//! removes a trigger an earlier generator emitted for it.

use super::{GenerateError, GeneratedOutput, Generator};
use crate::ast::{Model, NULL_STATE};
use crate::resolver::ResolvedSchema;
use crate::rules::DeclaredMachine;
use crate::utils::{to_pascal_case, to_snake_case};
use std::fmt::Write;
use std::path::PathBuf;

/// Emits a per-table state-transition check migration for each model with a machine.
pub struct StateTransitionCheckGenerator;

impl Default for StateTransitionCheckGenerator {
    fn default() -> Self {
        Self::new()
    }
}

/// A state as the column stores it: the enum's serde form, and `''` for unset.
fn stored(state: &str) -> String {
    if state == NULL_STATE {
        String::new()
    } else {
        to_snake_case(&to_pascal_case(state))
    }
}

fn sql_str(s: &str) -> String {
    format!("'{}'", s.replace('\'', "''"))
}

impl StateTransitionCheckGenerator {
    pub fn new() -> Self {
        Self
    }

    /// Whether a machine's states are the values its state field holds.
    fn checkable(model: &Model, machine: &DeclaredMachine) -> bool {
        use crate::ast::{PrimitiveType, TypeRef};
        let Some(field) = model.find_field(&machine.field) else { return false };
        let mut t = &field.type_ref;
        while let TypeRef::Optional(inner) = t {
            t = inner;
        }
        match t {
            // An enum, or text holding the state names themselves.
            TypeRef::Custom(_) | TypeRef::Primitive(PrimitiveType::String) => true,
            TypeRef::Primitive(PrimitiveType::Bool) => machine
                .transitions
                .iter()
                .flat_map(|tr| tr.from.iter().chain(std::iter::once(&tr.to)))
                .all(|s| matches!(s.as_str(), "true" | "false" | "*" | NULL_STATE)),
            _ => false,
        }
    }

    /// The models with a machine, each with its machines, in model order.
    fn machines<'a>(schema: &'a ResolvedSchema) -> Vec<(&'a Model, Vec<&'a DeclaredMachine>)> {
        schema
            .schema
            .models
            .iter()
            .filter_map(|m| {
                let ms: Vec<_> = schema
                    .schema
                    .rule_register
                    .machines
                    .iter()
                    .filter(|d| d.bound_model.as_deref() == Some(m.name.as_str()) && m.find_field(&d.field).is_some())
                    .collect();
                (!ms.is_empty()).then_some((m, ms))
            })
            .collect()
    }

    fn function_name(model: &Model, field: &str) -> String {
        let bare = format!("{}_{}_transition_check", model.collection_name(), field);
        match model.schema.as_deref().filter(|s| !s.is_empty()) {
            Some(s) => format!("{s}.{bare}"),
            None => bare,
        }
    }

    pub fn generate_up(model: &Model, machines: &[&DeclaredMachine]) -> String {
        let table = model.qualified_table_name();
        let mut out = String::new();
        writeln!(out, "-- State transitions declared for {}: an undeclared move is refused.", model.name).unwrap();
        writeln!(out, "-- Generated by metaphor-schema").unwrap();
        for m in machines {
            let field = &m.field;
            let function = Self::function_name(model, field);
            let trigger = format!("{}_{}_transition_check", model.collection_name(), field);
            let mut pairs: Vec<String> = Vec::new();
            let mut from_any: Vec<String> = Vec::new();
            for t in &m.transitions {
                let to = stored(&t.to);
                if t.from.is_empty() || t.from.iter().any(|f| f == "*") {
                    from_any.push(sql_str(&to));
                } else {
                    for f in &t.from {
                        pairs.push(format!("({}, {})", sql_str(&stored(f)), sql_str(&to)));
                    }
                }
            }
            pairs.sort();
            pairs.dedup();
            from_any.sort();
            from_any.dedup();
            let mut allowed = Vec::new();
            if !pairs.is_empty() {
                allowed.push(format!(
                    "(COALESCE(OLD.\"{field}\"::text, ''), COALESCE(NEW.\"{field}\"::text, '')) IN ({})",
                    pairs.join(", ")
                ));
            }
            if !from_any.is_empty() {
                allowed.push(format!("COALESCE(NEW.\"{field}\"::text, '') IN ({})", from_any.join(", ")));
            }
            let allowed = if allowed.is_empty() { "FALSE".to_string() } else { allowed.join("\n           OR ") };
            writeln!(out).unwrap();
            writeln!(out, "CREATE OR REPLACE FUNCTION {function}() RETURNS trigger LANGUAGE plpgsql AS $$").unwrap();
            writeln!(out, "BEGIN").unwrap();
            writeln!(out, "    IF NEW.\"{field}\" IS DISTINCT FROM OLD.\"{field}\" AND NOT (").unwrap();
            writeln!(out, "           {allowed}").unwrap();
            writeln!(out, "       ) THEN").unwrap();
            writeln!(
                out,
                "        RAISE EXCEPTION 'state_transition_not_declared: {table_name}.{field} % -> %', OLD.\"{field}\", NEW.\"{field}\"\n            USING ERRCODE = 'check_violation', COLUMN = '{field}', CONSTRAINT = 'tg_{table_name}__state_transition_not_declared';",
                table_name = model.collection_name(),
            )
            .unwrap();
            writeln!(out, "    END IF;").unwrap();
            writeln!(out, "    RETURN NEW;").unwrap();
            writeln!(out, "END $$;").unwrap();
            writeln!(out).unwrap();
            writeln!(out, "DROP TRIGGER IF EXISTS {trigger} ON {table};").unwrap();
            writeln!(out, "CREATE TRIGGER {trigger}").unwrap();
            writeln!(out, "    BEFORE UPDATE OF \"{field}\" ON {table}").unwrap();
            writeln!(out, "    FOR EACH ROW EXECUTE FUNCTION {function}();").unwrap();
        }
        out
    }

    fn generate_down(model: &Model, machines: &[&DeclaredMachine]) -> String {
        let table = model.qualified_table_name();
        let mut out = String::from("-- Generated by metaphor-schema\n");
        for m in machines {
            let trigger = format!("{}_{}_transition_check", model.collection_name(), m.field);
            writeln!(out, "DROP TRIGGER IF EXISTS {trigger} ON {table};").unwrap();
            writeln!(out, "DROP FUNCTION IF EXISTS {}();", Self::function_name(model, &m.field)).unwrap();
        }
        out
    }

    /// Timestamp slots after every table, audit-metadata and data-change-audit migration: the
    /// trigger attaches to a table that must already exist.
    fn slot_for(schema: &ResolvedSchema, index: usize) -> usize {
        let model_count = schema.schema.models.len();
        let enum_slot = if schema.schema.enums.is_empty() { 0 } else { 1 };
        let audited = schema.schema.models.iter().filter(|m| m.has_attribute("audited")).count();
        enum_slot + model_count + 3 + audited + index
    }
}

impl Generator for StateTransitionCheckGenerator {
    fn generate(&self, schema: &ResolvedSchema) -> Result<GeneratedOutput, GenerateError> {
        let mut output = GeneratedOutput::new();
        for (i, (model, machines)) in Self::machines(schema).into_iter().enumerate() {
            let ts = super::migration_timestamp_for(Self::slot_for(schema, i));
            let (checked, unchecked): (Vec<_>, Vec<_>) = machines.into_iter().partition(|m| Self::checkable(model, m));
            if !checked.is_empty() {
                let up = Self::generate_up(model, &checked);
                let mut h: u64 = 0xcbf29ce484222325;
                for b in up.bytes() {
                    h ^= b as u64;
                    h = h.wrapping_mul(0x100000001b3);
                }
                let base = format!("state_transition_check_{}_{:08x}", model.collection_name(), h as u32);
                output.add_file(PathBuf::from(format!("migrations/{ts}_{base}.up.sql")), up);
                output.add_file(PathBuf::from(format!("migrations/{ts}_{base}.down.sql")), Self::generate_down(model, &checked));
            }
            if !unchecked.is_empty() {
                let base = format!("drop_state_transition_check_{}", model.collection_name());
                let mut up = format!(
                    "-- {}: a machine whose states are not the values its column holds cannot be checked\n\
                     -- (named states on a bool field); remove a trigger an earlier generator emitted for it.\n\
                     -- Generated by metaphor-schema\n",
                    model.name
                );
                up.push_str(&Self::generate_down(model, &unchecked).replace("-- Generated by metaphor-schema\n", ""));
                output.add_file(PathBuf::from(format!("migrations/{ts}_{base}.up.sql")), up);
                output.add_file(PathBuf::from(format!("migrations/{ts}_{base}.down.sql")), "-- Generated by metaphor-schema\n-- Nothing to restore: the check this removed could not be made.\n".to_string());
            }
        }
        Ok(output)
    }

    fn name(&self) -> &'static str {
        "state_transition_check"
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::ast::{Field, ModuleSchema, PrimitiveType, TypeRef};

    fn schema() -> ResolvedSchema {
        let mut journal = Model::new("Journal");
        journal.schema = Some("accounting".into());
        journal.fields.push(Field::new("status", TypeRef::Primitive(PrimitiveType::String)));
        let mut s = ModuleSchema::new("accounting");
        s.models = vec![journal];
        let hook = "module: accounting\nstate_machines:\n  - entity: Journal\n    field: status\n    states: [draft, approved, posted, voided]\n    transitions:\n      - { from: draft, to: approved, on: approve }\n      - { from: [approved, draft], to: posted, on: post }\n      - { from: \"*\", to: voided, on: void }\n";
        s.rule_register.read_file("journal.hook.yaml", hook);
        s.rule_register.bind(&s.models.clone());
        ResolvedSchema { schema: s }
    }

    #[test]
    fn a_machine_gets_a_refusing_trigger_listing_its_declared_moves() {
        let out = StateTransitionCheckGenerator::new().generate(&schema()).unwrap();
        let (path, up) = out
            .files
            .iter()
            .find(|(p, _)| p.to_string_lossy().contains("_state_transition_check_journals_") && p.to_string_lossy().ends_with(".up.sql"))
            .expect("one migration for the journal table");
        assert!(path.to_string_lossy().starts_with("migrations/"));
        // Another declared move changes the text, so it lands as a new migration, never a rewrite.
        let mut more = schema();
        more.schema.rule_register = Default::default();
        let hook = "module: accounting\nstate_machines:\n  - entity: Journal\n    field: status\n    states: [draft, approved, posted, voided]\n    transitions:\n      - { from: draft, to: approved, on: approve }\n";
        more.schema.rule_register.read_file("journal.hook.yaml", hook);
        more.schema.rule_register.bind(&more.schema.models.clone());
        let other = StateTransitionCheckGenerator::new().generate(&more).unwrap();
        assert!(!other.files.contains_key(path), "a changed machine is a new migration");
        assert!(up.contains("CREATE OR REPLACE FUNCTION accounting.journals_status_transition_check() RETURNS trigger"), "{up}");
        assert!(up.contains("('approved', 'posted'), ('draft', 'approved'), ('draft', 'posted')"), "{up}");
        assert!(up.contains("COALESCE(NEW.\"status\"::text, '') IN ('voided')"), "a move from any state: {up}");
        assert!(up.contains("RAISE EXCEPTION 'state_transition_not_declared: journals.status % -> %'"), "{up}");
        assert!(
            up.contains("USING ERRCODE = 'check_violation', COLUMN = 'status', CONSTRAINT = 'tg_journals__state_transition_not_declared'"),
            "answered as a violation on the field: {up}"
        );
        assert!(!up.contains("RAISE WARNING"), "{up}");
        assert!(up.contains("BEFORE UPDATE OF \"status\" ON accounting.journals"), "{up}");
    }

    #[test]
    fn a_bool_field_with_named_states_gets_its_trigger_dropped_not_added() {
        let mut limit = Model::new("SessionLimit");
        limit.schema = Some("sapiens".into());
        limit.fields.push(Field::new("enforce_limit", TypeRef::Primitive(PrimitiveType::Bool)));
        let mut event = Model::new("SecurityEvent");
        event.schema = Some("sapiens".into());
        event.fields.push(Field::new("resolved", TypeRef::Primitive(PrimitiveType::Bool)));
        let mut s = ModuleSchema::new("sapiens");
        s.models = vec![limit, event];
        let hook = "module: sapiens\nstate_machines:\n  - entity: SessionLimit\n    field: enforce_limit\n    transitions:\n      - { from: unenforced, to: enforced, on: enable }\n  - entity: SecurityEvent\n    field: resolved\n    transitions:\n      - { from: \"false\", to: \"true\", on: resolve }\n";
        s.rule_register.read_file("x.hook.yaml", hook);
        s.rule_register.bind(&s.models.clone());
        let out = StateTransitionCheckGenerator::new().generate(&ResolvedSchema { schema: s }).unwrap();
        let names: Vec<String> = out.files.keys().map(|p| p.file_name().unwrap().to_string_lossy().into_owned()).collect();
        assert!(names.iter().any(|n| n.ends_with("_drop_state_transition_check_session_limits.up.sql")), "{names:?}");
        assert!(!names.iter().any(|n| n.contains("add_state_transition_check_session_limits")), "{names:?}");
        assert!(names.iter().any(|n| n.contains("_state_transition_check_security_events_") && n.ends_with(".up.sql")), "true/false states are checkable: {names:?}");
        let drop = out.files.iter().find(|(p, _)| p.to_string_lossy().ends_with("_drop_state_transition_check_session_limits.up.sql")).unwrap().1;
        assert!(drop.contains("DROP TRIGGER IF EXISTS session_limits_enforce_limit_transition_check ON sapiens.session_limits;"), "{drop}");
        assert!(drop.contains("DROP FUNCTION IF EXISTS sapiens.session_limits_enforce_limit_transition_check();"), "{drop}");
    }

    #[test]
    fn a_model_without_a_machine_gets_no_migration() {
        let mut s = schema();
        s.schema.rule_register.machines.clear();
        assert!(StateTransitionCheckGenerator::new().generate(&s).unwrap().files.is_empty());
    }
}
