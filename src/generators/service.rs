//! Service generator
//!
//! Phase 1: Generates a **type alias** over `GenericCrudService` instead of a
//! full CRUD implementation per entity.
//!
//! ## Before (was 250+ generated lines per entity):
//! ```rust,ignore
//! pub struct OrderService { repository: Arc<OrderRepository>, ... }
//! impl OrderService { pub async fn list(...) { ... } ... }  // 12 methods
//! ```
//!
//! ## After (3 generated lines per entity):
//! ```rust,ignore
//! pub type OrderService = GenericCrudService<
//!     Order, CreateOrderDto, UpdateOrderDto, OrderRepository
//! >;
//! ```
//!
//! Custom behaviour is added via a decorator in `*_service_custom.rs` (never regenerated).

use super::{
    build_generated_path, build_subdirectory_mod, GenerateError, GeneratedOutput, Generator,
};
use crate::ast::Model;
use crate::resolver::ResolvedSchema;
use std::fmt::Write;
use std::path::PathBuf;

/// Generates application service type aliases from schema
pub struct ServiceGenerator {
    /// Group generated files by model/domain
    group_by_domain: bool,
}

impl ServiceGenerator {
    pub fn new() -> Self {
        Self {
            group_by_domain: false,
        }
    }

    pub fn with_group_by_domain(mut self, group: bool) -> Self {
        self.group_by_domain = group;
        self
    }

    /// Generate a type alias file for a single entity's service.
    fn generate_service_alias(&self, schema: &crate::ast::ModuleSchema, model: &Model) -> String {
        let mut output = String::new();
        let name = &model.name;
        let snake_name = to_snake_case(name);

        writeln!(output, "//! Application service for {} entities", name).unwrap();
        writeln!(output, "//!").unwrap();
        writeln!(
            output,
            "//! Generated by metaphor-schema. Do not edit manually."
        )
        .unwrap();
        writeln!(output, "//!").unwrap();
        writeln!(
            output,
            "//! Type alias over `GenericCrudService` — all CRUD logic lives in backbone-core."
        )
        .unwrap();
        writeln!(
            output,
            "//! For custom behaviour, create `{}_service_custom.rs` (preserved on regen).",
            snake_name
        )
        .unwrap();
        writeln!(output).unwrap();

        writeln!(output, "use backbone_core::GenericCrudService;").unwrap();
        writeln!(output).unwrap();
        writeln!(
            output,
            "use crate::presentation::dto::{{Create{}Dto, Update{}Dto}};",
            name, name
        )
        .unwrap();
        writeln!(output, "use crate::domain::entity::{};", name).unwrap();
        writeln!(
            output,
            "use crate::infrastructure::persistence::{}Repository;",
            name
        )
        .unwrap();
        writeln!(output).unwrap();

        writeln!(output, "/// Application service for {} entities.", name).unwrap();
        writeln!(output, "///").unwrap();
        writeln!(
            output,
            "/// All 12 standard CRUD operations (list, create, get, update, patch,"
        )
        .unwrap();
        writeln!(
            output,
            "/// soft_delete, restore, empty_trash, bulk_create, upsert, find_by_id,"
        )
        .unwrap();
        writeln!(
            output,
            "/// list_deleted) are provided by `GenericCrudService`."
        )
        .unwrap();
        writeln!(output, "///").unwrap();
        writeln!(
            output,
            "/// Custom extensions go in `{}_service_custom.rs`:",
            snake_name
        )
        .unwrap();
        writeln!(output, "///").unwrap();
        writeln!(output, "/// ```rust,ignore").unwrap();
        writeln!(output, "/// pub struct {}ServiceCustom {{", name).unwrap();
        writeln!(output, "///     inner: Arc<{}Service>,", name).unwrap();
        writeln!(output, "///     // add domain-specific dependencies here").unwrap();
        writeln!(output, "/// }}").unwrap();
        writeln!(output, "/// ```").unwrap();
        writeln!(output, "pub type {}Service = GenericCrudService<", name).unwrap();
        writeln!(output, "    {},", name).unwrap();
        writeln!(output, "    Create{}Dto,", name).unwrap();
        writeln!(output, "    Update{}Dto,", name).unwrap();
        writeln!(output, "    {}Repository,", name).unwrap();
        writeln!(output, ">;").unwrap();
        // A model whose service file is hand-owned gets its guard in a file of its own.
        if crate::rules::compile::model_has_guard(schema, model) && !schema.hand_owned_services.contains(&model.name) {
            output.push_str(&Self::guard_items(schema, model));
        }
        writeln!(output).unwrap();
        writeln!(output, "// <<< CUSTOM").unwrap();
        writeln!(output, "// END CUSTOM").unwrap();

        output
    }

    fn guard_items(schema: &crate::ast::ModuleSchema, model: &Model) -> String {
        let rules = crate::rules::compile::model_row_rules(schema, model);
        let deletes = crate::rules::compile::model_delete_guards(schema, model);
        let state_fields = crate::rules::compile::model_state_fields(schema, model);
        crate::rules::compile::render_guard(model, &rules, &deletes, &state_fields)
    }

    /// The guard of a model whose service file is hand-owned, as a generated file of its own.
    fn guard_file(schema: &crate::ast::ModuleSchema, model: &Model) -> String {
        format!(
            "//! The write guard of {name} (generated by metaphor-schema; do not edit). It lives in a\n\
             //! file of its own because `{snake}_service.rs` is hand-owned.\n\n\
             #[allow(unused_imports)]\n\
             use super::*;\n\
             use crate::domain::entity::{name};\n{guard}",
            name = model.name,
            snake = to_snake_case(&model.name),
            guard = Self::guard_items(schema, model)
        )
    }

    /// Generate the error.rs module — now a simple re-export from backbone-core.
    fn generate_error_module(&self) -> String {
        let mut output = String::new();
        writeln!(output, "//! Service error types").unwrap();
        writeln!(output, "//!").unwrap();
        writeln!(
            output,
            "//! Generated by metaphor-schema. Do not edit manually."
        )
        .unwrap();
        writeln!(output, "//!").unwrap();
        writeln!(
            output,
            "//! Re-exported from backbone-core so that existing `super::error::ServiceError`"
        )
        .unwrap();
        writeln!(output, "//! import paths continue to work without change.").unwrap();
        writeln!(output).unwrap();
        writeln!(
            output,
            "pub use backbone_core::{{ServiceError, ServiceResult}};"
        )
        .unwrap();
        output
    }
}

impl Default for ServiceGenerator {
    fn default() -> Self {
        Self::new()
    }
}

impl Generator for ServiceGenerator {
    fn generate(&self, schema: &ResolvedSchema) -> Result<GeneratedOutput, GenerateError> {
        let mut output = GeneratedOutput::new();

        let model_names: Vec<String> = schema
            .schema
            .models
            .iter()
            .map(|m| m.name.clone())
            .collect();

        for model in &schema.schema.models {
            let model_snake = to_snake_case(&model.name);
            if schema.schema.hand_owned_services.contains(&model.name)
                && crate::rules::compile::model_has_guard(&schema.schema, model)
            {
                output.add_file(
                    PathBuf::from(format!("src/application/service/{model_snake}_row_rules.rs")),
                    Self::guard_file(&schema.schema, model),
                );
            }
            let service_content = self.generate_service_alias(&schema.schema, model);

            if self.group_by_domain {
                let service_path = build_generated_path(
                    "src/application/service",
                    &model.name,
                    &format!("{}_service.rs", model_snake),
                    true,
                );
                output.add_file(service_path, service_content);

                let sub_mod_path =
                    PathBuf::from(format!("src/application/service/{}/mod.rs", model_snake));
                let sub_mod_content =
                    build_subdirectory_mod(&model.name, &format!("{}_service", model_snake));
                output.add_file(sub_mod_path, sub_mod_content);
            } else {
                let service_path = PathBuf::from(format!(
                    "src/application/service/{}_service.rs",
                    model_snake
                ));
                output.add_file(service_path, service_content);
            }
        }

        // error.rs — re-export from backbone-core
        output.add_file(
            PathBuf::from("src/application/service/error.rs"),
            self.generate_error_module(),
        );

        // mod.rs
        if !schema.schema.models.is_empty() {
            let mut mod_content = String::new();
            writeln!(mod_content, "//! Application services").unwrap();
            writeln!(mod_content, "//!").unwrap();
            writeln!(
                mod_content,
                "//! Generated by metaphor-schema. Do not edit manually."
            )
            .unwrap();
            writeln!(mod_content, "//!").unwrap();
            writeln!(
                mod_content,
                "//! Each entity service is a type alias over `GenericCrudService`."
            )
            .unwrap();
            writeln!(mod_content).unwrap();

            writeln!(mod_content, "pub mod error;").unwrap();
            writeln!(
                mod_content,
                "pub use error::{{ServiceError, ServiceResult}};"
            )
            .unwrap();
            writeln!(mod_content).unwrap();

            if self.group_by_domain {
                for model in &model_names {
                    let model_snake = to_snake_case(model);
                    writeln!(mod_content, "pub mod {};", model_snake).unwrap();
                }
                writeln!(mod_content).unwrap();
                for model in &model_names {
                    let model_snake = to_snake_case(model);
                    writeln!(mod_content, "pub use {}::{}Service;", model_snake, model).unwrap();
                }
                for model in &schema.schema.models {
                    if crate::rules::compile::model_has_guard(&schema.schema, model) {
                        writeln!(mod_content, "pub use {}::{}RowRules;", to_snake_case(&model.name), model.name).unwrap();
                    }
                }
            } else {
                for model in &schema.schema.models {
                    writeln!(
                        mod_content,
                        "pub mod {}_service;",
                        to_snake_case(&model.name)
                    )
                    .unwrap();
                }
                writeln!(mod_content).unwrap();
                writeln!(mod_content, "// <<< CUSTOM").unwrap();
                writeln!(mod_content, "// END CUSTOM").unwrap();
                writeln!(mod_content).unwrap();
                for model in &schema.schema.models {
                    writeln!(
                        mod_content,
                        "pub use {}_service::{}Service;",
                        to_snake_case(&model.name),
                        model.name
                    )
                    .unwrap();
                }
                for model in &schema.schema.models {
                    if !crate::rules::compile::model_has_guard(&schema.schema, model) {
                        continue;
                    }
                    let snake = to_snake_case(&model.name);
                    if schema.schema.hand_owned_services.contains(&model.name) {
                        writeln!(mod_content, "pub mod {snake}_row_rules;").unwrap();
                        writeln!(mod_content, "pub use {snake}_row_rules::{}RowRules;", model.name).unwrap();
                    } else {
                        writeln!(mod_content, "pub use {snake}_service::{}RowRules;", model.name).unwrap();
                    }
                }
                writeln!(mod_content, "// <<< CUSTOM").unwrap();
                writeln!(mod_content, "// END CUSTOM").unwrap();
            }

            output.add_file(PathBuf::from("src/application/service/mod.rs"), mod_content);
        }

        Ok(output)
    }

    fn name(&self) -> &'static str {
        "service"
    }
}

use crate::utils::to_snake_case;

#[cfg(test)]
mod tests {
    use super::*;
    use crate::ast::{Attribute, Field, ModuleSchema, PrimitiveType, TypeRef};

    fn create_test_model() -> Model {
        let mut model = Model::new("Order");
        model.fields = vec![
            Field {
                name: "id".to_string(),
                type_ref: TypeRef::Primitive(PrimitiveType::Uuid),
                attributes: vec![Attribute::new("id")],
                ..Default::default()
            },
            Field {
                name: "name".to_string(),
                type_ref: TypeRef::Primitive(PrimitiveType::String),
                attributes: vec![],
                ..Default::default()
            },
        ];
        model
    }

    fn create_test_schema() -> ResolvedSchema {
        let mut schema = ModuleSchema::new("test");
        schema.models.push(create_test_model());
        ResolvedSchema { schema }
    }

    /// The test schema with one row rule on `Order` and one rule the compiler does not take.
    fn schema_with_rules() -> ResolvedSchema {
        let mut resolved = create_test_schema();
        let hook = "name: OrderRules\nmodel: Order\nrules:\n  name_length:\n    when: [create, update]\n    condition: \"name.length <= 80\"\n    code: NAME_TOO_LONG\n  only_owner:\n    when: [update]\n    condition: \"$actor.can('admin')\"\n";
        let models = resolved.schema.models.clone();
        let register = &mut resolved.schema.rule_register;
        register.read_file("order.hook.yaml", hook);
        register.bind(&models);
        register.check(&models);
        register.mark_compiled(&models, &Default::default());
        resolved
    }

    #[test]
    fn a_declared_row_rule_compiles_into_the_service_guard_in_shadow() {
        let resolved = schema_with_rules();
        let output = ServiceGenerator::new().generate(&resolved).unwrap();
        let service = &output.files[&PathBuf::from("src/application/service/order_service.rs")];
        assert!(service.contains("pub struct OrderRowRules;"), "{service}");
        assert!(service.contains("impl backbone_core::write_guard::WriteGuard<Order> for OrderRowRules"));
        assert!(service.contains("r::le(r::length(r::field(row, \"name\")), r::Val::Num(80.0_f64))"));
        assert!(service.contains("Violation::new(\"name\", \"name_too_long\""));
        assert!(service.contains("GuardOutcome { refuse: Vec::new(), shadow }"));
        // A writer check a rule cannot make: no check for it, and it stays unenforced.
        assert!(!service.contains("only_owner"));
        let statuses: Vec<_> = resolved.schema.rule_register.rules.iter().map(|r| (r.name.as_str(), r.status)).collect();
        assert_eq!(
            statuses,
            vec![
                ("name_length", crate::rules::EnforcementStatus::Shadow),
                ("only_owner", crate::rules::EnforcementStatus::Unenforced)
            ]
        );
        let module = &output.files[&PathBuf::from("src/application/service/mod.rs")];
        assert!(module.contains("pub use order_service::OrderRowRules;"));
        let lib = crate::generators::module::ModuleGenerator::new().generate(&resolved).unwrap();
        let lib = &lib.files[&PathBuf::from("src/lib.rs")];
        assert!(lib.contains(".with_guard(Arc::new(crate::application::service::OrderRowRules))"), "{lib}");
    }

    #[test]
    fn a_hand_owned_service_gets_its_guard_in_a_file_of_its_own() {
        let mut resolved = schema_with_rules();
        resolved.schema.hand_owned_services.insert("Order".into());
        let output = ServiceGenerator::new().generate(&resolved).unwrap();
        let guard = &output.files[&PathBuf::from("src/application/service/order_row_rules.rs")];
        assert!(guard.contains("pub struct OrderRowRules;") && guard.contains("use crate::domain::entity::Order;"), "{guard}");
        let service = &output.files[&PathBuf::from("src/application/service/order_service.rs")];
        assert!(!service.contains("OrderRowRules"), "the hand-owned file is not where the guard goes");
        let module = &output.files[&PathBuf::from("src/application/service/mod.rs")];
        assert!(module.contains("pub mod order_row_rules;") && module.contains("pub use order_row_rules::OrderRowRules;"), "{module}");
    }

    #[test]
    fn a_service_without_row_rules_has_no_guard() {
        let output = ServiceGenerator::new().generate(&create_test_schema()).unwrap();
        let service = &output.files[&PathBuf::from("src/application/service/order_service.rs")];
        assert!(!service.contains("RowRules"));
        let lib = crate::generators::module::ModuleGenerator::new().generate(&create_test_schema()).unwrap();
        assert!(!lib.files[&PathBuf::from("src/lib.rs")].contains("with_guard"));
    }

    #[test]
    fn test_service_generator_creates_files() {
        let schema = create_test_schema();
        let generator = ServiceGenerator::new();
        let output = generator.generate(&schema).unwrap();

        assert!(output
            .files
            .contains_key(&PathBuf::from("src/application/service/order_service.rs")));
        assert!(output
            .files
            .contains_key(&PathBuf::from("src/application/service/mod.rs")));
        assert!(output
            .files
            .contains_key(&PathBuf::from("src/application/service/error.rs")));
    }

    #[test]
    fn test_service_emits_type_alias() {
        let schema = create_test_schema();
        let generator = ServiceGenerator::new();
        let output = generator.generate(&schema).unwrap();

        let content = output
            .files
            .get(&PathBuf::from("src/application/service/order_service.rs"))
            .unwrap();

        assert!(content.contains("pub type OrderService = GenericCrudService<"));
        assert!(content.contains("GenericCrudService"));
        assert!(content.contains("CreateOrderDto"));
        assert!(content.contains("UpdateOrderDto"));
        assert!(content.contains("OrderRepository"));
    }

    #[test]
    fn test_error_module_re_exports_backbone_core() {
        let schema = create_test_schema();
        let generator = ServiceGenerator::new();
        let output = generator.generate(&schema).unwrap();

        let error_content = output
            .files
            .get(&PathBuf::from("src/application/service/error.rs"))
            .unwrap();

        assert!(error_content.contains("backbone_core"));
        assert!(error_content.contains("ServiceError"));
        assert!(error_content.contains("ServiceResult"));
    }

    #[test]
    fn test_service_has_custom_marker() {
        let schema = create_test_schema();
        let generator = ServiceGenerator::new();
        let output = generator.generate(&schema).unwrap();

        let content = output
            .files
            .get(&PathBuf::from("src/application/service/order_service.rs"))
            .unwrap();

        assert!(content.contains("<<< CUSTOM"));
        assert!(content.contains("END CUSTOM"));
    }
}
