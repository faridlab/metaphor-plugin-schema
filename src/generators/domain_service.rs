//! Domain service generator
//!
//! Emits the module file of `src/domain/services/`: the home of a module's hand-written domain
//! services, mounted through the directory's extension (`mod.ext.rs`).
//!
//! It no longer emits a `DomainPolicy` per model. No write path ever consulted one, so the
//! rules a model declares compile into its service's write guard instead (`<Model>RowRules`,
//! checked on every generic write), and the policy files retire on the next full generation.

use super::{GenerateError, GeneratedOutput, Generator};
use crate::resolver::ResolvedSchema;
use std::fmt::Write;
use std::path::PathBuf;

/// Generates the domain services module file.
pub struct DomainServiceGenerator;

impl DomainServiceGenerator {
    pub fn new() -> Self {
        Self
    }

    /// Kept for the generator registry's builder; domain services are not grouped by model.
    pub fn with_group_by_domain(self, _group: bool) -> Self {
        self
    }
}

impl Default for DomainServiceGenerator {
    fn default() -> Self {
        Self::new()
    }
}

impl Generator for DomainServiceGenerator {
    fn generate(&self, schema: &ResolvedSchema) -> Result<GeneratedOutput, GenerateError> {
        let mut output = GeneratedOutput::new();
        if schema.schema.models.is_empty() {
            return Ok(output);
        }
        let mut mod_content = String::new();
        writeln!(mod_content, "//! Domain services").unwrap();
        writeln!(mod_content, "//!").unwrap();
        writeln!(mod_content, "//! Generated by metaphor-schema. Do not edit manually.").unwrap();
        writeln!(mod_content, "//!").unwrap();
        writeln!(
            mod_content,
            "//! Hand-written domain services live beside this file and are mounted by its extension."
        )
        .unwrap();
        writeln!(
            mod_content,
            "//! A model's declared rules are checked by its service's write guard."
        )
        .unwrap();
        writeln!(mod_content).unwrap();
        writeln!(mod_content, "// <<< CUSTOM").unwrap();
        writeln!(mod_content, "// END CUSTOM").unwrap();
        output.add_file(PathBuf::from("src/domain/services/mod.rs"), mod_content);
        Ok(output)
    }

    fn name(&self) -> &'static str {
        "domain_service"
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::ast::{Attribute, Field, Model, ModuleSchema, PrimitiveType, TypeRef};

    fn create_test_schema() -> ResolvedSchema {
        let mut model = Model::new("Order");
        model.fields = vec![Field {
            name: "id".to_string(),
            type_ref: TypeRef::Primitive(PrimitiveType::Uuid),
            attributes: vec![Attribute::new("id")],
            ..Default::default()
        }];
        let mut schema = ModuleSchema::new("test");
        schema.models.push(model);
        ResolvedSchema { schema }
    }

    #[test]
    fn only_the_services_module_file_is_emitted() {
        let out = DomainServiceGenerator::new().generate(&create_test_schema()).unwrap();
        let paths: Vec<_> = out.files.keys().cloned().collect();
        assert_eq!(paths, vec![PathBuf::from("src/domain/services/mod.rs")], "no domain policy per model");
        let content = &out.files[&PathBuf::from("src/domain/services/mod.rs")];
        assert!(!content.contains("DomainPolicy"));
    }
}
