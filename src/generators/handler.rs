//! REST Handler generator
//!
//! Generates Axum handlers that integrate with backbone-core's BackboneCrudHandler.
//! Routes are generated with relative paths (e.g., `/users`) to be nested under a module prefix.
//! When mounted at `/api/v1/{module}`, implements all 14 standard Backbone CRUD endpoints:
//! 1. GET /{collection} - List (paginated, filtered, sorted)
//! 2. POST /{collection} - Create
//! 3. GET /{collection}/:id - Get by ID
//! 4. PUT /{collection}/:id - Full update
//! 5. PATCH /{collection}/:id - Partial update
//! 6. DELETE /{collection}/:id - Soft delete
//! 7. POST /{collection}/bulk - Bulk create
//! 8. POST /{collection}/upsert - Upsert
//! 9. GET /{collection}/trash - List deleted (paginated, filtered)
//! 10. POST /{collection}/:id/restore - Restore
//! 11. DELETE /{collection}/empty - Empty trash
//! 12. GET /{collection}/:id/deleted - Get deleted by ID
//! 13. DELETE /{collection}/trash/:id - Permanent delete from trash
//! 14. GET /{collection}/count - Count active/deleted entities

