    fn a_transition_answers_without_the_models_secrets() {
        use crate::ast::{hook::{StateMachine, Transition}, Attribute};
        let field = |name: &str, attrs: Vec<Attribute>| Field {
            name: name.to_string(),
            type_ref: TypeRef::Primitive(PrimitiveType::String),
            attributes: attrs,
            ..Default::default()
        };
        let sm = StateMachine {
            field: "status".to_string(),
            transitions: vec![Transition { name: "revoke".into(), from: vec!["active".into()], to: "revoked".into(), ..Default::default() }],
            ..Default::default()
        };
        let render = |model: &Model| {
            let mut out = String::new();
            HandlerGenerator::new().write_transition_handlers(&mut out, model, "SessionState", &sm, None).unwrap();
            out
        };
        let state = || Field { name: "status".into(), type_ref: TypeRef::Custom("SessionStatus".into()), ..Default::default() };
        let secret = Model { name: "Session".into(), fields: vec![state(), field("token_hash", vec![Attribute::new("sensitive")])], ..Default::default() };
        let out = render(&secret);
        assert!(out.contains("backbone_core::http::without_secrets::<Session, _>(response)"), "{out}");
        assert!(out.contains("ApiResponse::<serde_json::Value>::not_found"), "every arm answers the same type");
        assert!(!out.contains("ApiResponse::<SessionResponseDto>"), "no arm is typed with the DTO: {out}");

        let plain = Model { name: "Ticket".into(), fields: vec![state()], ..Default::default() };
        let out = render(&plain);
        assert!(!out.contains("without_secrets") && out.contains("ApiResponse::<TicketResponseDto>::not_found"), "unchanged output without secrets");
    }

    #[test]
    fn a_transition_writes_the_state_as_the_enum_reads_it_and_runs_as_its_verb() {
        use crate::ast::hook::{StateMachine, Transition};
        let sm = StateMachine {
            field: "status".to_string(),
            transitions: vec![Transition { name: "put_on_hold".into(), from: vec!["active".into()], to: "on_hold".into(), ..Default::default() }],
            ..Default::default()
        };
        let model = Model {
            name: "Ticket".into(),
            fields: vec![Field { name: "status".into(), type_ref: TypeRef::Custom("TicketStatus".into()), ..Default::default() }],
            ..Default::default()
        };
        let mut out = String::new();
        HandlerGenerator::new().write_transition_handlers(&mut out, &model, "TicketState", &sm, None).unwrap();
        // snake_case, the enum's serde form; PascalCase ("OnHold") deserialized into nothing.
        assert!(out.contains("serde_json::Value::String(\"on_hold\".to_string())"), "{out}");
        assert!(!out.contains("\"OnHold\""), "{out}");
        assert!(out.contains("backbone_core::write_guard::as_transition(\"put_on_hold\", service.partial_update(&id, fields))"), "{out}");
        // A label the PascalCase round trip loses (`moved_301` reads `moved301`) is written as the
        // SQL type spells it.
        let sm301 = StateMachine {
            field: "status".to_string(),
            transitions: vec![Transition { name: "relocate".into(), from: vec!["active".into()], to: "moved_301".into(), ..Default::default() }],
            ..Default::default()
        };
        let mut out301 = String::new();
        HandlerGenerator::new().write_transition_handlers(&mut out301, &model, "TicketState", &sm301, None).unwrap();
        assert!(out301.contains("serde_json::Value::String(\"moved_301\".to_string())"), "{out301}");
        // A refused transition answers with the service's status (422 with its violations, 404,
        // 409), not a blanket 500.
        assert!(out.contains("Err(e) => backbone_core::http::service_error_response::<TicketResponseDto>(&e),"), "{out}");
        assert!(!out.contains("Err(e) => (StatusCode::INTERNAL_SERVER_ERROR"), "{out}");
        // An unreadable stored state is refused, never read as the initial state.
        assert!(out.contains("StatusCode::CONFLICT") && !out.contains("unwrap_or(TicketState::default())"), "{out}");
        // The caller's permission is checked whatever the module's features, and an unknown
        // caller is refused rather than let through.
        assert!(!out.contains("cfg(feature = \"auth\")"), "no permission check behind a feature: {out}");
        assert!(out.contains("auth: Option<axum::Extension<AuthContext>>,") && out.contains("StatusCode::UNAUTHORIZED"), "{out}");

        // A verb with roles names them in the shadow log as plain words: quoted names would end
        // the generated string literal early.
        let with_roles = StateMachine {
            transitions: vec![Transition { name: "lock".into(), from: vec!["active".into()], to: "locked".into(), allowed_roles: vec!["admin".into(), "owner".into()], ..Default::default() }],
            ..sm.clone()
        };
        let mut roles_out = String::new();
        HandlerGenerator::new().write_transition_handlers(&mut roles_out, &model, "TicketState", &with_roles, None).unwrap();
        assert!(roles_out.contains("or one of the roles admin, owner"), "{roles_out}");
        // Permissions match with wildcards, as serpa's `*:*` superuser grant needs.
        assert!(out.contains("let has_specific_perm = granted(\"ticket:transition:put_on_hold\");"), "{out}");
        assert!(out.contains("have.last() == Some(&\"*\")"), "{out}");
        assert!(!roles_out.contains("[\"admin\""), "{roles_out}");

        // A state field that is not an enum (a bool `resolved`) gets no routes, never another column.
        let flag = Model {
            name: "Ticket".into(),
            fields: vec![
                Field { name: "resolved".into(), type_ref: TypeRef::Primitive(PrimitiveType::Bool), ..Default::default() },
                Field { name: "kind".into(), type_ref: TypeRef::Custom("TicketKind".into()), ..Default::default() },
            ],
            ..Default::default()
        };
        let sm_flag = StateMachine { field: "resolved".into(), ..sm.clone() };
        let mut none = String::new();
        HandlerGenerator::new().write_transition_handlers(&mut none, &flag, "TicketState", &sm_flag, None).unwrap();
        assert!(none.contains("No transition routes") && !none.contains("\"kind\"") && !none.contains("transition_routes("), "{none}");
    }

